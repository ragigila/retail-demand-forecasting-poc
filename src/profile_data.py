"""Stage 1: profile pseudonymised ILE. Every number in data_profile.md comes from this script.
usage: python profile_data.py [config.yaml]"""
import os
import sys

import numpy as np
import pandas as pd

from common import load_config, load_pseudonymised, load_items, md_table

cfg = load_config(sys.argv[1] if len(sys.argv) > 1 else None)
P = cfg["profile"]
df, info, id_map = load_pseudonymised(cfg)
items = load_items(cfg, id_map)
out = cfg["paths"]["out_dir"]
os.makedirs(out, exist_ok=True)
md = []


def H(t, lvl=2):
    md.append("\n" + "#" * lvl + " " + t + "\n")


def T(df_, **k):
    md.append(md_table(df_, **k) + "\n")


def L(t):
    md.append(t + "\n")


# ---- cutoff ---------------------------------------------------------------------------------------------
cut = pd.Timestamp(cfg["period"]["last_full_week_end"])
n_after = int((df["date"] > cut).sum())
df = df[df["date"] <= cut].copy()
df["week"] = df["date"].dt.to_period("W-SUN").dt.start_time  # ISO week start (Monday)
last_week = cut.to_period("W-SUN").start_time
first_week = df["week"].min()

md.append("# Data profile - Stage 1 (ILE Business Central, pseudonymised)\n")
L("Generated by `profile_data.py`; all numbers computed from the extract. IDs are random (SKU_xxxxx, LOC_xx); the mapping file is kept private.")

# ---- 1. overview ----------------------------------------------------------------------------------------
H("1. Overview")
ov = pd.DataFrame([
    ("Files loaded (brand x month)", info["files"]), ("Rows read", info["rows_raw"]),
    ("Duplicate Entry_No dropped", info["duplicate_entry_no"]),
    ("Rows after cutoff (excluded)", n_after), ("Rows analysed", len(df)),
    ("Posting_Date min", str(df["date"].min().date())), ("Posting_Date max (<= cutoff)", str(df["date"].max().date())),
    ("Cutoff (last full ISO week end)", str(cut.date())),
    ("Distinct items (SKU)", df["sku"].nunique()), ("Distinct locations", df["loc"].nunique()),
    ("Distinct (SKU x location) pairs", len(df.groupby(["loc", "sku"]).size())),
], columns=["Metric", "Value"])
T(ov)
H("Rows per brand", 3)
T(df.groupby("brand").agg(rows=("entry_no", "size"), items=("sku", "nunique"), locations=("loc", "nunique")).reset_index())

# ---- 2. entry types -------------------------------------------------------------------------------------
H("2. Entry Type")
et = df.groupby("entry_type").agg(rows=("entry_no", "size"), qty_sum=("qty", "sum")).reset_index()
et["share_%"] = 100 * et["rows"] / et["rows"].sum()
T(et)
H("Entry Type x Document Type", 3)
T(df.groupby(["entry_type", "doc_type"]).size().rename("rows").reset_index())
piv = df.pivot_table(index="loc", columns="entry_type", values="entry_no", aggfunc="size", fill_value=0)
piv["TOTAL"] = piv.sum(axis=1)
piv.reset_index().to_csv(os.path.join(out, "entries_by_type_by_location.csv"), index=False)
L(f"Entries per Entry Type per location: {len(piv)} locations - full table in `entries_by_type_by_location.csv`.")

# ---- 3. transfers ---------------------------------------------------------------------------------------
H("3. How Transfers are recorded")
tr = df[df["entry_type"] == "Transfer"]
L(f"Transfer rows: {len(tr):,}; with blank Order_No: {int((tr['order'] < 0).sum()):,}.")
trk = tr[tr["order"] >= 0]
L(f"Shipment-side rows (qty<0): {int((trk['qty'] < 0).sum()):,}; receipt-side rows (qty>0): {int((trk['qty'] > 0).sum()):,}; qty=0 rows: {int((trk['qty'] == 0).sum()):,}.")
per_to = trk.assign(ship_q=trk["qty"].clip(upper=0), recv_q=trk["qty"].clip(lower=0)).groupby("order").agg(ship_q=("ship_q", "sum"), recv_q=("recv_q", "sum"))
per_to["has_s"] = per_to["ship_q"] < 0
per_to["has_r"] = per_to["recv_q"] > 0
L(f"Transfer Orders seen: {len(per_to):,}; with both a shipment and a receipt entry in this extract: {int((per_to.has_s & per_to.has_r).sum()):,}; "
  f"shipment only: {int((per_to.has_s & ~per_to.has_r).sum()):,}; receipt only: {int((~per_to.has_s & per_to.has_r).sum()):,}.")
bal = per_to[per_to.has_s & per_to.has_r]
L(f"Of TOs with both sides, quantity balanced (ship = -recv): {int(np.isclose(bal.ship_q, -bal.recv_q).sum()):,} of {len(bal):,}.")
line = trk.groupby(["order", "sku"]).agg(net=("qty", "sum")).reset_index()
L(f"TO x SKU lines: {len(line):,}; net quantity = 0: {int((line['net'] == 0).sum()):,}; net != 0: {int((line['net'] != 0).sum()):,} "
  f"(net>0 {int((line['net'] > 0).sum()):,}, net<0 {int((line['net'] < 0).sum()):,}).")
sg = trk.assign(neg=trk["qty"] < 0, posi=trk["qty"] > 0).groupby(["order", "loc"]).agg(neg=("neg", "any"), posi=("posi", "any"))
both_same_loc = sg["neg"] & sg["posi"]
L(f"(Transfer Order, location) combinations that hold BOTH a shipment and a receipt entry (would indicate an in-transit location posting both legs): "
  f"{int(both_same_loc.sum()):,} of {len(both_same_loc):,}.")
tl = tr.assign(ship=(tr["qty"] < 0).astype(int), recv=(tr["qty"] > 0).astype(int)).groupby("loc").agg(
    ship_rows=("ship", "sum"), recv_rows=("recv", "sum"), net_qty=("qty", "sum")).reset_index()
tl["recv/ship"] = tl["recv_rows"] / tl["ship_rows"].replace(0, np.nan)
cand = tl[(tl["ship_rows"] > 0) & tl["recv/ship"].between(0.9, 1.1) & (tl["net_qty"].abs() <= 0.02 * (tl["ship_rows"] + tl["recv_rows"]))]
L(f"Locations whose transfer in/out look symmetric (recv/ship rows 0.9-1.1 and |net qty| <= 2% of rows) - possible in-transit-like pass-through: {len(cand)}.")
L(f"Dimension 1 equals Location Code in {100 * df['dim1_eq_loc'].mean():.1f}% of rows overall; for Transfer rows {100 * tr['dim1_eq_loc'].mean():.1f}%.")

# ---- 4. returns / corrections --------------------------------------------------------------------------
H("4. Returns and corrections")
L("The Item Ledger Entry OData page exposes no `Correction` field (checked in a full sample record and in metadata), so reversals can only be inferred from quantity sign and document structure.")
sale = df[df["entry_type"] == "Sale"]
posr = sale[sale["qty"] > 0]
out_units = -sale.loc[sale["qty"] < 0, "qty"].sum()
L(f"Sale rows: {len(sale):,}; with positive qty (returns): {len(posr):,} ({100 * len(posr) / max(len(sale), 1):.2f}%); "
  f"positive qty sum {posr['qty'].sum():,.0f} vs sale outflow {out_units:,.0f} ({100 * posr['qty'].sum() / max(out_units, 1):.2f}% of units).")
sgn = np.sign(sale["qty"]).map({-1.0: "qty<0", 1.0: "qty>0", 0.0: "qty=0"}).rename("sign")
T(sale.groupby(["doc_type", sgn]).size().rename("rows").reset_index())
sd = sale.assign(neg=sale["qty"] < 0, posi=sale["qty"] > 0).groupby(["doc", "loc", "sku"]).agg(neg=("neg", "any"), posi=("posi", "any"))
L(f"Sale (document, location, SKU) groups containing both a negative and a positive entry (same-document reversal pattern): {int((sd.neg & sd.posi).sum()):,}.")
L(f"Sale rows with zero Sales Amount: {int((sale['sales_amt'] == 0).sum()):,} ({100 * (sale['sales_amt'] == 0).mean():.1f}%).")
if items is not None:
    nm_sku = set(items.loc[items["department"].fillna("").astype(str).isin(P["non_merch_department_codes"]), "sku"])
    sale_nm = sale["sku"].isin(nm_sku)
    L(f"Sale rows on non-merchandise items (Item Card department in {P['non_merch_department_codes']}): {int(sale_nm.sum()):,} ({100 * sale_nm.mean():.1f}% of Sale rows); "
      f"zero Sales Amount share: non-merch {100 * (sale.loc[sale_nm, 'sales_amt'] == 0).mean():.1f}% vs merchandise {100 * (sale.loc[~sale_nm, 'sales_amt'] == 0).mean():.1f}%.")
adj = df[df["entry_type"].isin(["Positive Adjmt.", "Negative Adjmt."])]
L(f"Adjustment rows: {len(adj):,}; in the first data week (opening balance): {int((adj['week'] == first_week).sum()):,}.")

# ---- 5. location type proposal -------------------------------------------------------------------------
H("5. Location type proposal (to be confirmed)")
d0 = df.assign(is_sale=(df["entry_type"] == "Sale"), is_purch=(df["entry_type"] == "Purchase"),
               is_tout=(df["entry_type"] == "Transfer") & (df["qty"] < 0), is_tin=(df["entry_type"] == "Transfer") & (df["qty"] > 0))
lt = d0.groupby("loc").agg(rows=("entry_no", "size"), sale_rows=("is_sale", "sum"), purchase_rows=("is_purch", "sum"),
                           transfer_out_rows=("is_tout", "sum"), transfer_in_rows=("is_tin", "sum"),
                           brands=("brand", lambda s: "/".join(sorted(s.unique())))).reset_index()
lt["sale_share"] = lt["sale_rows"] / lt["rows"]


def classify(r):
    if r.sale_rows == 0:
        return "warehouse_or_other"
    if r.sale_share >= P["store_min_sale_share"] and r.purchase_rows == 0:
        return "store"
    if r.sale_share <= P["warehouse_max_sale_share"] and r.purchase_rows > 0:
        return "warehouse"
    return "AMBIGUOUS"


lt["proposed_type"] = lt.apply(classify, axis=1)
lt.to_csv(os.path.join(out, "location_type_proposal.csv"), index=False)
L(f"Rule (config.yaml): no Sale rows -> warehouse_or_other; sale share >= {P['store_min_sale_share']} and no Purchase rows -> store; "
  f"sale share <= {P['warehouse_max_sale_share']} with Purchase rows -> warehouse; otherwise AMBIGUOUS.")
T(lt.groupby("proposed_type").agg(locations=("loc", "size"), rows=("rows", "sum"), sale_rows=("sale_rows", "sum")).reset_index())
amb = lt[lt["proposed_type"] != "store"].sort_values("rows", ascending=False)
H("Non-store locations (pseudonymised IDs)", 3)
T(amb[["loc", "brands", "rows", "sale_rows", "purchase_rows", "transfer_out_rows", "transfer_in_rows", "sale_share", "proposed_type"]], floatfmt="{:,.3f}")
L("Full per-location table: `location_type_proposal.csv`. Real codes are only in the private `id_map.json`.")
ltype = lt.set_index("loc")["proposed_type"]

# ---- 6. series: provisional demand ---------------------------------------------------------------------
H("6. Series history, intermittency, SBC class")
L("Provisional demand (NOT yet the confirmed definition): store = -(Sale qty) summed per ISO week (returns netted); "
  "warehouse = -(Transfer qty<0) per ISO week. AMBIGUOUS and warehouse_or_other locations are excluded here.")
d = df.assign(type=df["loc"].map(ltype))
first_any = d.groupby(["loc", "sku"])["week"].min().rename("first_entry_week")
dem = pd.concat([
    d[(d.type == "store") & (d.entry_type == "Sale")].assign(dq=lambda x: -x["qty"]),
    d[(d.type == "warehouse") & (d.entry_type == "Transfer") & (d.qty < 0)].assign(dq=lambda x: -x["qty"]),
])
wk = dem.groupby(["type", "loc", "sku", "week"])["dq"].sum().reset_index()
wk["nz"] = (wk["dq"] > 0).astype(int)
wk["neg"] = (wk["dq"] < 0).astype(int)
wk["pos"] = wk["dq"].clip(lower=0)
wk["pos2"] = wk["pos"] ** 2
agg = wk.groupby(["loc", "sku"]).agg(nz_weeks=("nz", "sum"), neg_weeks=("neg", "sum"), s1=("pos", "sum"), s2=("pos2", "sum"),
                                     first_dem_week=("week", "min"))
s = first_any.to_frame().join(agg)
s["type"] = s.index.get_level_values("loc").map(ltype)
s = s[s["type"].isin(["store", "warehouse"])].copy()
for c in ["nz_weeks", "neg_weeks", "s1", "s2"]:
    s[c] = s[c].fillna(0)
s["n_weeks"] = (last_week - s["first_entry_week"]).dt.days // 7 + 1
s["n_weeks_from_first_demand"] = (last_week - s["first_dem_week"]).dt.days // 7 + 1
s["zero_pct"] = 100 * (1 - s["nz_weeks"] / s["n_weeks"])
mean = s["s1"] / s["nz_weeks"].replace(0, np.nan)
cv2 = ((s["s2"] / s["nz_weeks"].replace(0, np.nan) - mean ** 2).clip(lower=0)) / mean ** 2
adi = s["n_weeks"] / s["nz_weeks"].replace(0, np.nan)
cls = np.select(
    [s["nz_weeks"] == 0, s["nz_weeks"] < 2, (adi < P["sbc_adi_cut"]) & (cv2 < P["sbc_cv2_cut"]), (adi < P["sbc_adi_cut"]),
     (cv2 < P["sbc_cv2_cut"])],
    ["no_demand", "insufficient(1 nonzero week)", "smooth", "erratic", "intermittent"], default="lumpy")
s["adi"] = adi
s["cv2"] = cv2
s["class"] = cls
s = s.reset_index()
if items is not None:
    s = s.merge(items[["sku", "category", "dcs", "department"]], on="sku", how="left")
    s["non_merch"] = s["department"].fillna("").astype(str).isin(P["non_merch_department_codes"])
else:
    s["non_merch"] = False
L(f"Series (SKU x location) in provisional store/warehouse locations: {len(s):,}. Series start = first ILE entry of any type at that SKU x location "
  f"(stock presence); series end = last full ISO week ({last_week.date()}). Max possible length = {int((last_week - first_week).days // 7 + 1)} weeks.")


def lens(x, col):
    return pd.Series({"series": len(x), "min": x[col].min(), "median": x[col].median(), "max": x[col].max(),
                      f"<{P['short_history_weeks']}w": int((x[col] < P["short_history_weeks"]).sum())})


rows = []
for t in ["store", "warehouse"]:
  for nm in [False, True]:
    x = s[(s["type"] == t) & (s["non_merch"] == nm)]
    tag = "non-merch" if nm else "merch"
    if len(x):
        rows.append(pd.concat([pd.Series({"type": t, "items": tag, "basis": "all series, start=first entry"}), lens(x, "n_weeks")]))
    xd = x[x["nz_weeks"] > 0]
    if len(xd):
        rows.append(pd.concat([pd.Series({"type": t, "items": tag, "basis": "series with demand, start=first demand week"}), lens(xd, "n_weeks_from_first_demand")]))
T(pd.DataFrame(rows))
L("Percent of weeks with zero demand per series (start = first entry), series with >=1 demand week:")
zr = []
for t in ["store", "warehouse"]:
  for nm in [False, True]:
    x = s[(s["type"] == t) & (s["nz_weeks"] > 0) & (s["non_merch"] == nm)]
    if len(x):
        zr.append({"type": t, "items": "non-merch" if nm else "merch", "series": len(x), "zero_pct_median": x["zero_pct"].median(), "p25": x["zero_pct"].quantile(.25),
                   "p75": x["zero_pct"].quantile(.75), "series_zero_pct>=50": int((x["zero_pct"] >= 50).sum()),
                   "series_with_negative_week": int((x["neg_weeks"] > 0).sum())})
T(pd.DataFrame(zr))
H("SBC classification (ADI cut %.2f, CV2 cut %.2f)" % (P["sbc_adi_cut"], P["sbc_cv2_cut"]), 3)
s["items"] = np.where(s["non_merch"], "non-merch", "merch")
cc = s.groupby(["type", "items", "class"]).size().rename("series").reset_index()
cc["share_in_group_%"] = 100 * cc["series"] / cc.groupby(["type", "items"])["series"].transform("sum")
T(cc)
if items is not None:
    H("Item master join", 3)
    L(f"Ledger items found in Item Card: {100 * s['dcs'].notna().mean():.1f}% of series; category non-empty: "
      f"{100 * (s['category'].fillna('') != '').mean():.1f}%; non-merchandise (department {P['non_merch_department_codes']}) series: "
      f"{int(s['non_merch'].sum()):,} ({100 * s['non_merch'].mean():.1f}%).")
    L("Category hierarchy comes from the configured item attributes (department / class / DCS). Top departments among series (non-merch flagged):")
    T(s.groupby(["department", "non_merch"], dropna=False).size().rename("series").reset_index().sort_values("series", ascending=False).head(12))
else:
    L("Item master file not available - category/non-merchandise section skipped.")

# ---- 7. truncated-history check -----------------------------------------------------------------------
H("7. Stock-balance check (feeds the stockout proxy)")
x = df.sort_values(["loc", "sku", "entry_no"]).copy()
x["cum"] = x.groupby(["loc", "sku"])["qty"].cumsum()
mn = x.groupby(["loc", "sku"])["cum"].min()
fe = x.groupby(["loc", "sku"]).first()
open_adj = (fe["entry_type"] == "Positive Adjmt.") & (fe["week"] == first_week)
L(f"(SKU x location) pairs: {len(mn):,}; whose running balance ever goes negative (balance start unknown or posting-order effects): "
  f"{int((mn < -1e-9).sum()):,} ({100 * (mn < -1e-9).mean():.1f}%).")
L(f"Pairs whose first entry is a Positive Adjmt. in the first data week (go-live opening balance): {int(open_adj.sum()):,} ({100 * open_adj.mean():.1f}%).")
L(f"Pairs whose first entry is in the first data week: {int((fe['week'] == first_week).sum()):,} ({100 * (fe['week'] == first_week).mean():.1f}%).")

with open(os.path.join(out, "data_profile.md"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(md))
s.to_csv(os.path.join(out, "series_profile_pseudonymised.csv"), index=False)
print("wrote", os.path.join(out, "data_profile.md"))
